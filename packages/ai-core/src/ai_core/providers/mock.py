import asyncio
from typing import AsyncIterator
from ai_core.base import BaseProvider, LLMConfig, StreamChunk, GenerationResult


class MockProvider(BaseProvider):
    """
    Mock AI Provider generating simulated responses for offline development and testing.
    """

    async def generate(self, prompt: str, config: LLMConfig) -> GenerationResult:
        content = f"Mock response for prompt: '{prompt}'. (Configure GEMINI_API_KEY or OPENAI_API_KEY for live completions)."
        return GenerationResult(
            content=content,
            model_name="mock-provider",
        )

    async def stream(self, prompt: str, config: LLMConfig) -> AsyncIterator[StreamChunk]:
        paragraphs = [
            f"**GraphMind Simulated Response** for: *'{prompt}'*\n\n",
            "This is a simulated token stream generated by `MockProvider` because no active API key was detected.\n\n",
            "• **Provider Abstraction**: Working as designed via `packages/ai-core`.\n",
            "• **Live Streaming**: Server-Sent Events (SSE) streaming tokens to the graph canvas node.\n\n",
            "Set `GEMINI_API_KEY` in your `.env` file to stream live Google Gemini completions!",
        ]
        for paragraph in paragraphs:
            for word in paragraph.split(" "):
                yield StreamChunk(content=word + " ")
                await asyncio.sleep(0.04)
